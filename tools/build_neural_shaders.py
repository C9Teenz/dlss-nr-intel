"""Compile the neural HLSL (src/compute/neural_passes.hlsl, neural_blocks.hlsl) to DXIL and
embed it as src/neural/embedded_neural_dxil.h (the scheme of src/graph/embedded_graph_dxil.h).

    python tools/build_neural_shaders.py [--dxc path/to/dxc.exe]

Run after editing the HLSL; the header is committed so the C++ build needs no DXC.
"""
from __future__ import annotations

import argparse
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
COMPUTE = ROOT / "src" / "compute"
HEADER = ROOT / "src" / "neural" / "embedded_neural_dxil.h"
DEFAULT_DXC = ROOT / "third_party" / "dxc" / "extracted" / "build" / "native" / "bin" / "x64" / "dxc.exe"   # NuGet 1.8.2407
# (source, entry, symbol, profile): the blocks use [WaveSize(16)], which needs SM 6.6
ENTRIES = (("neural_passes.hlsl", "CSNeuralPre", "kNeuralPreDxil", "cs_6_0"),
           ("neural_passes.hlsl", "CSNeuralPost", "kNeuralPostDxil", "cs_6_0"),
           ("neural_passes.hlsl", "CSHeadStabilize", "kNeuralStabilizeDxil", "cs_6_0"),
           ("neural_passes.hlsl", "CSMotion", "kNeuralMotionDxil", "cs_6_0"),
           ("neural_passes.hlsl", "CSHeadCommit", "kNeuralCommitDxil", "cs_6_0"),
           ("neural_passes.hlsl", "CSFieldColour", "kNeuralFieldColourDxil", "cs_6_0"),
           ("neural_passes.hlsl", "CSRefCommit", "kNeuralRefCommitDxil", "cs_6_0"),
           ("neural_passes.hlsl", "CSWarpMotion", "kNeuralWarpMotionDxil", "cs_6_0"),
           ("neural_passes.hlsl", "CSHeadWarp", "kNeuralHeadWarpDxil", "cs_6_0"),
           ("neural_passes.hlsl", "CSGuideFit", "kNeuralGuideFitDxil", "cs_6_0"),
           ("neural_passes.hlsl", "CSGuideSmooth", "kNeuralGuideSmoothDxil", "cs_6_0"),
           ("neural_passes.hlsl", "CSCoarseSums", "kNeuralCoarseSumsDxil", "cs_6_0"),
           ("neural_passes.hlsl", "CSCoarseFit", "kNeuralCoarseFitDxil", "cs_6_0"),
           ("neural_passes.hlsl", "CSQuarterCur", "kNeuralQuarterCurDxil", "cs_6_0"),
           ("neural_passes.hlsl", "CSQuarterRef", "kNeuralQuarterRefDxil", "cs_6_0"),
           ("neural_passes.hlsl", "CSWarpPyramid", "kNeuralWarpPyramidDxil", "cs_6_0"),
           ("neural_passes.hlsl", "CSStepMotion", "kNeuralStepMotionDxil", "cs_6_0"),
           ("neural_passes.hlsl", "CSChain", "kNeuralChainDxil", "cs_6_0"),
           ("neural_passes.hlsl", "CSKeepLuma", "kNeuralKeepLumaDxil", "cs_6_0"),
           ("neural_blocks.hlsl", "CSWindowBlock32", "kWindowBlock32Dxil", "cs_6_6"),
           ("neural_blocks.hlsl", "CSPool2", "kPool2Dxil", "cs_6_6"),
           ("neural_blocks.hlsl", "CSPoolProject", "kPoolProjectDxil", "cs_6_6"),
           ("neural_blocks_wide.hlsl", "CSBranchedFFN", "kBranchedFfnDxil", "cs_6_6"),
           ("neural_blocks_wide.hlsl", "CSProjectResidual", "kProjectResidualDxil", "cs_6_6"),
           ("neural_blocks_wide.hlsl", "CSWindowAttention", "kWindowAttentionDxil", "cs_6_6"),
           ("neural_blocks_wide.hlsl", "CSPoolProjectN", "kPoolProjectNDxil", "cs_6_6"),
           ("neural_blocks_wide.hlsl", "CSUpMerge", "kUpMergeDxil", "cs_6_6"),
           ("neural_blocks_wide.hlsl", "CSGate", "kGateDxil", "cs_6_6"),
           ("neural_blocks_wide.hlsl", "CSResidual", "kResidualDxil", "cs_6_6"),
           ("neural_blocks_wide.hlsl", "CSWindowAttentionQKV", "kWindowAttentionQkvDxil", "cs_6_6"),
           ("neural_blocks_wide.hlsl", "CSGlobalAttention", "kGlobalAttentionDxil", "cs_6_6"),
           ("neural_blocks_wide.hlsl", "CSQuantize", "kQuantizeDxil", "cs_6_6"))


# precision=fast (NeuralOptions::precise false): every block kernel again without the E4M3 publishes
# and with the one-pass softmax, as k<Name>FastDxil
ENTRIES += tuple((source + "|E4M3=0", entry, symbol.replace("Dxil", "FastDxil"), profile)
                 for source, entry, symbol, profile in ENTRIES if source.startswith("neural_blocks"))


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--dxc", type=Path, default=DEFAULT_DXC)
    args = parser.parse_args()
    if not args.dxc.is_file():
        sys.exit(f"dxc not found at {args.dxc}")
    lines = ["#pragma once", "// Generated by tools/build_neural_shaders.py from src/compute/neural_*.hlsl.",
             "#include <cstdint>", "#include <cstddef>", "namespace dlss_nr::neural::embedded {"]
    with tempfile.TemporaryDirectory() as tmp:
        for source, entry, symbol, profile in ENTRIES:
            source, _, define = source.partition("|")       # "file.hlsl|NAME=VALUE": a -D variant
            out = Path(tmp) / f"{symbol}.dxil"
            cmd = [str(args.dxc), "-nologo", "-T", profile, "-E", entry, "-O3", "-Fo", str(out), str(COMPUTE / source)]
            if define:
                cmd.insert(1, f"-D{define}")
            if profile >= "cs_6_2":
                cmd.insert(1, "-enable-16bit-types")   # half is a real 16-bit type, dot2add available
            result = subprocess.run(cmd, capture_output=True, text=True)
            if result.returncode != 0:
                sys.exit(f"dxc failed for {entry}:\n{result.stdout}{result.stderr}")
            data = out.read_bytes()
            body = ", ".join(f"0x{b:02x}" for b in data)
            lines.append(f"alignas(8) inline constexpr uint8_t {symbol}[{len(data)}] = {{ {body} }};")
            print(f"{entry}: {len(data)} bytes")
    lines.append("} // namespace dlss_nr::neural::embedded")
    HEADER.parent.mkdir(parents=True, exist_ok=True)
    HEADER.write_text("\n".join(lines) + "\n")
    print(f"wrote {HEADER}")


if __name__ == "__main__":
    main()
